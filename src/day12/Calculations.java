package day12;

public class Calculations
{
    public void addition(int a, int b)
    {
        int sum =a+b;
        System.out.println("Addition: " +sum);
    }


    //changed the count of parameters
    public void addition(int a, int b, int c)
    {
        int sum =a+b;
        System.out.println("Addition: " +sum);
    }

    //changed the data type of parameter
    public void addition(int a, byte b)
    {
        int sum =a+b;
        System.out.println("Addition: " +sum);
    }

    //changed the order of parameters
    public void addition(byte a, int b)
    {
        int sum =a+b;
        System.out.println("Addition: " +sum);
    }


    public void addition(byte a, byte b)
    {
        int sum =a+b;
        System.out.println("Addition: " +sum);
    }

    public void addition(int a, int b, double c)
    {
        int sum =a+b;
        System.out.println("Addition: " +sum);
    }


}
