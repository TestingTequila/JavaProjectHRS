package day4;

public class IncrementOperators {
    public static void main(String[] args) {

        int a = 1;
        int b = a;
        System.out.println(a);//1
        System.out.println(b);//1

        int c = 2000;
        int d = c;
        System.out.println(c); //2000
        System.out.println(d); //2000
    }
}
