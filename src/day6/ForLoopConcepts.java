package day6;

public class ForLoopConcepts {


    public static void main(String[] args) {

        System.out.println("=======1. WAP to Print my name 10 times==================");


        for (int i = 1; i <= 10; i++) {
            System.out.println("Ashish");
        }


        System.out.println("=======2. WAP to Print my numbers from 1-10 ==================");

        for (int j = 1; j <= 10; j++) {
            System.out.println(j);

        }

        System.out.println("=======3. WAP to Print my numbers from 10-1 ==================");


        for (int k = 10; k > 0; k--) {
            System.out.println(k);

        }


        System.out.println("=======3. WAP to Print table of 2 ==================");
        for (int m = 1; m <= 10; m++) {
            System.out.println(2 * m);

        }

    }
}
